import assert from 'node:assert/strict';
import fs from 'node:fs';
const source = fs.readFileSync(new URL('../web/stream.js', import.meta.url), 'utf8');
const { default: register } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
let spec, tick, response = {text: 'Начало'};
globalThis.setInterval = f => (tick = f, 1);
globalThis.fetch = async () => ({ok:true, json:async () => response});
register({addSlot(place, value) { assert.equal(place, 'session.composer'); spec = value; }});
const root = {hidden: false, textContent: '', classList: {add(){}}};
spec.render(root, {}, {session:{name:'проверка',state:'busy'}});
await new Promise(r => setImmediate(r));
assert.equal(root.textContent, 'Начало');
assert.equal(root.hidden, false);
response = {text: 'Начало ответа'}; await tick();
assert.equal(root.textContent, 'Начало ответа');
response = {text: ''}; await tick();
assert.equal(root.hidden, true);
spec.render(root, {}, {session:{name:'другая',state:'idle'}});
assert.equal(root.textContent, '');
console.log('Предварительный текст обновляется и скрывается');
